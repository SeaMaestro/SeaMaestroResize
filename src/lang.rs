#[derive(Clone, Copy, PartialEq, Eq, Default)]
pub enum Lang {
    #[default]
    En,
    Ru,
    Uk,
    De,
    Es,
    Fr,
    El,
    Fil,
}

impl Lang {
    pub fn from_code(s: &str) -> Option<Lang> {
        match s.to_ascii_lowercase().as_str() {
            "en" | "eng" | "english" => Some(Lang::En),
            "ru" | "rus" | "russian" => Some(Lang::Ru),
            "uk" | "ua" | "ukrainian" => Some(Lang::Uk),
            "de" | "ger" | "german" => Some(Lang::De),
            "es" | "spa" | "spanish" => Some(Lang::Es),
            "fr" | "fre" | "french" => Some(Lang::Fr),
            "el" | "gr" | "greek" => Some(Lang::El),
            "fil" | "tl" | "tagalog" => Some(Lang::Fil),
            _ => None,
        }
    }

    pub fn detect(stem: &str) -> Lang {
        let lower = stem.to_ascii_lowercase();
        for w in lower.split(|c: char| !c.is_ascii_alphabetic()) {
            if let Some(l) = Lang::from_code(w) {
                return l;
            }
        }
        Lang::En
    }
}

pub fn messages(lang: Lang) -> &'static Messages {
    match lang {
        Lang::En => &EN,
        Lang::Ru => &RU,
        Lang::Uk => &UK,
        Lang::De => &DE,
        Lang::Es => &ES,
        Lang::Fr => &FR,
        Lang::El => &EL,
        Lang::Fil => &FIL,
    }
}

// The message tables below are consts, not test items: keeping this module first is deliberate, so
// moving it to the end of the file would bury every real change in an unreadable diff.
#[allow(clippy::items_after_test_module)]
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_language_fills_the_exif_notes_and_keeps_the_placeholder_count() {
        // The compiler already guarantees that every locale fills the fields; what it cannot see is an
        // empty string or a translation that dropped (or added) a `{}` — that is what this covers.
        for m in [EN, RU, UK, DE, ES, FR, EL, FIL] {
            assert!(!m.note_exif_not_kept.trim().is_empty(), "empty exif note in a locale");
            assert!(!m.note_exif_rewrite_failed.trim().is_empty(), "empty exif note in a locale");
            assert_eq!(
                m.note_exif_not_kept.matches("{}").count(),
                EN.note_exif_not_kept.matches("{}").count(),
                "a translation has a different placeholder count than EN"
            );
            assert_eq!(
                m.note_exif_rewrite_failed.matches("{}").count(),
                EN.note_exif_rewrite_failed.matches("{}").count(),
                "a translation has a different placeholder count than EN"
            );
        }
    }

    fn row_texts(rows: &'static [HelpRow]) -> Vec<&'static str> {
        let mut out = Vec::new();
        for row in rows {
            match *row {
                HelpRow::Title(s) | HelpRow::Text(s) | HelpRow::HiText(s) => out.push(s),
                HelpRow::Pair(a, b) => {
                    out.push(a);
                    out.push(b);
                }
            }
        }
        out
    }

    #[test]
    fn help_examples_run_on_windows() {
        for code in ["en", "ru", "uk", "de", "es", "fr", "el", "fil"] {
            let lang = Lang::from_code(code).expect("known language code");
            let m = messages(lang);
            assert!(
                !m.after_help.contains("seamaestro"),
                "[{code}] help still shows the POSIX name 'seamaestro'"
            );
            assert!(
                !m.after_help.contains("cat photo.jpg"),
                "[{code}] help still pipes through 'cat' (POSIX)"
            );
            assert!(
                m.after_help.contains("SeaMaestro.exe"),
                "[{code}] help lost the Windows executable name"
            );
            for intro in [m.help_intro_normal, m.help_intro_cut] {
                for text in row_texts(intro) {
                    assert!(
                        !text.contains("seamaestro"),
                        "[{code}] help intro still shows 'seamaestro': {text}"
                    );
                }
            }
        }
    }
}

