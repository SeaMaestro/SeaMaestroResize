#[derive(Clone, Copy, PartialEq, Eq, Default)]
pub enum Lang {
    #[default]
    En,
    Ru,
    Uk,
    De,
    Es,
    Fr,
    El,
    Fil,
}

impl Lang {
    pub fn from_code(s: &str) -> Option<Lang> {
        match s.to_ascii_lowercase().as_str() {
            "en" | "eng" | "english" => Some(Lang::En),
            "ru" | "rus" | "russian" => Some(Lang::Ru),
            "uk" | "ua" | "ukrainian" => Some(Lang::Uk),
            "de" | "ger" | "german" => Some(Lang::De),
            "es" | "spa" | "spanish" => Some(Lang::Es),
            "fr" | "fre" | "french" => Some(Lang::Fr),
            "el" | "gr" | "greek" => Some(Lang::El),
            "fil" | "tl" | "tagalog" => Some(Lang::Fil),
            _ => None,
        }
    }

    pub fn detect(stem: &str) -> Lang {
        let lower = stem.to_ascii_lowercase();
        for w in lower.split(|c: char| !c.is_ascii_alphabetic()) {
            if let Some(l) = Lang::from_code(w) {
                return l;
            }
        }
        Lang::En
    }
}

pub fn messages(lang: Lang) -> &'static Messages {
    match lang {
        Lang::En => &EN,
        Lang::Ru => &RU,
        Lang::Uk => &UK,
        Lang::De => &DE,
        Lang::Es => &ES,
        Lang::Fr => &FR,
        Lang::El => &EL,
        Lang::Fil => &FIL,
    }
}

